-- ============================================================================
-- ColdTrace - Esquema de referencia para Supabase (PostgreSQL)
-- ============================================================================
-- OPCIONAL. Con `spring.jpa.hibernate.ddl-auto=update` (perfil prod) Hibernate
-- crea estas mismas tablas en el primer arranque del backend.
--
-- Usa este script si prefieres crear el esquema manualmente desde
-- Supabase Dashboard -> SQL Editor.
--
-- Idempotente: se puede ejecutar varias veces sin errores.
-- ============================================================================

CREATE TABLE IF NOT EXISTS usuario (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    rol      VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS producto (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(255) NOT NULL,
    tipo               VARCHAR(255) NOT NULL,
    temperatura_minima FLOAT8 NOT NULL,
    temperatura_maxima FLOAT8 NOT NULL,
    vida_util_dias     INTEGER
);

CREATE TABLE IF NOT EXISTS lote (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(255) NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    estado            VARCHAR(255) NOT NULL,
    producto_id       BIGINT NOT NULL,
    CONSTRAINT fk_lote_producto FOREIGN KEY (producto_id) REFERENCES producto (id)
);

CREATE TABLE IF NOT EXISTS registro_temperatura (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    temperatura    FLOAT8 NOT NULL,
    fecha_registro TIMESTAMP(6),
    ubicacion      VARCHAR(255),
    lote_id        BIGINT NOT NULL,
    CONSTRAINT fk_registro_lote FOREIGN KEY (lote_id) REFERENCES lote (id)
);

CREATE TABLE IF NOT EXISTS operacion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manifiesto     VARCHAR(255) NOT NULL,
    transportista  VARCHAR(255) NOT NULL,
    tipo_producto  VARCHAR(255) NOT NULL,
    inspector      VARCHAR(255) NOT NULL,
    firma          VARCHAR(255),
    evidencia      VARCHAR(255),
    fecha_registro TIMESTAMP(6),
    estado         VARCHAR(255),
    lote_id        BIGINT,
    CONSTRAINT fk_operacion_lote FOREIGN KEY (lote_id) REFERENCES lote (id)
);

CREATE TABLE IF NOT EXISTS operacion_controles_confirmados (
    operacion_id          BIGINT NOT NULL,
    controles_confirmados VARCHAR(255),
    CONSTRAINT fk_controles_operacion FOREIGN KEY (operacion_id) REFERENCES operacion (id)
);

CREATE INDEX IF NOT EXISTS idx_lote_producto ON lote (producto_id);
CREATE INDEX IF NOT EXISTS idx_registro_lote ON registro_temperatura (lote_id);
CREATE INDEX IF NOT EXISTS idx_operacion_lote ON operacion (lote_id);
